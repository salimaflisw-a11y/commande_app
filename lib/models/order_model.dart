import 'package:cloud_firestore/cloud_firestore.dart';
import 'cart_item_model.dart';

class OrderModel {
  final String id;
  final DateTime createdAt;
  final String customerName;
  final String customerPhone;
  final String orderType; // 'Sur place', 'À emporter', 'Livraison'
  final String? tableNumber;
  final String? deliveryAddress;
  final String paymentMethod; // 'Paiement au comptoir'
  final String specialNotes;
  final List<CartItemModel> items;
  final double subtotalHt;
  final double vatRate;
  final double vatAmount;
  final double totalTtc;

  /// Status pour l'admin : 'En attente', 'Livrée', 'Rejetée'
  final String status;

  /// Statut du paiement pour la table livrée : 'unpaid' (Non payée) ou 'paid' (Payée)
  final String paymentStatus;

  /// Vrai si le client a quitté le restaurant sans régler la note
  final bool clientLeftWithoutPaying;

  final bool isSentToManager;

  /// Deadline by which the client must pay (set when order is confirmed).
  /// null means no deadline set yet.
  final DateTime? paymentDeadline;

  /// Secret verification code generated by the system, visible only on cashier's screen
  /// and encoded in cashier QR code. Required to validate payment.
  final String? paymentSecurityCode;

  const OrderModel({
    required this.id,
    required this.createdAt,
    required this.customerName,
    required this.customerPhone,
    required this.orderType,
    this.tableNumber,
    this.deliveryAddress,
    required this.paymentMethod,
    this.specialNotes = '',
    required this.items,
    required this.subtotalHt,
    this.vatRate = 0.10,
    required this.vatAmount,
    required this.totalTtc,
    this.status = 'En attente',
    this.paymentStatus = 'unpaid',
    this.clientLeftWithoutPaying = false,
    this.isSentToManager = true,
    this.paymentDeadline,
    this.paymentSecurityCode,
  });

  int get totalItemCount =>
      items.fold(0, (acc, item) => acc + item.quantity);

  bool get isPending => status == 'En attente';
  bool get isDelivered => status == 'Livrée';
  bool get isRejected => status == 'Rejetée';
  bool get isPaid => paymentStatus == 'paid';
  bool get isUnpaid => paymentStatus == 'unpaid';
  bool get isBlockedDueToUnpaid => clientLeftWithoutPaying;

  /// True when a payment deadline exists and has already passed without payment.
  bool get isPaymentOverdue {
    if (isPaid) return false;
    if (paymentDeadline == null) return false;
    return DateTime.now().isAfter(paymentDeadline!);
  }

  /// Remaining time until the payment deadline (null if no deadline).
  Duration? get remainingPaymentTime {
    if (paymentDeadline == null) return null;
    final remaining = paymentDeadline!.difference(DateTime.now());
    return remaining.isNegative ? Duration.zero : remaining;
  }

  /// True if the client has an active (not yet expired) payment deadline.
  bool get hasActivePaymentTimer =>
      !isPaid && paymentDeadline != null && !isPaymentOverdue;

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'createdAt': createdAt.toIso8601String(),
      'customerName': customerName,
      'customerPhone': customerPhone,
      'orderType': orderType,
      'tableNumber': tableNumber,
      'deliveryAddress': deliveryAddress,
      'paymentMethod': paymentMethod,
      'specialNotes': specialNotes,
      'subtotalHt': subtotalHt,
      'vatRate': vatRate,
      'vatAmount': vatAmount,
      'totalTtc': totalTtc,
      'status': status,
      'paymentStatus': paymentStatus,
      'clientLeftWithoutPaying': clientLeftWithoutPaying,
      'isSentToManager': isSentToManager,
      'paymentDeadline': paymentDeadline?.toIso8601String(),
      'paymentSecurityCode': paymentSecurityCode,
    };
  }

  factory OrderModel.fromJson(Map<String, dynamic> json) {
    // Handle both Firestore Timestamp and ISO string
    DateTime parseDate(dynamic v) {
      if (v is Timestamp) return v.toDate();
      if (v is String) return DateTime.tryParse(v) ?? DateTime.now();
      return DateTime.now();
    }

    final rawItems = json['items'] as List<dynamic>? ?? [];

    return OrderModel(
      id: json['id'] as String? ?? '',
      createdAt: parseDate(json['createdAt']),
      customerName: json['customerName'] as String? ?? '',
      customerPhone: json['customerPhone'] as String? ?? '',
      orderType: json['orderType'] as String? ?? '',
      tableNumber: json['tableNumber'] as String?,
      deliveryAddress: json['deliveryAddress'] as String?,
      paymentMethod: json['paymentMethod'] as String? ?? '',
      specialNotes: json['specialNotes'] as String? ?? '',
      items: rawItems
          .map((e) => CartItemModel.fromJson(e as Map<String, dynamic>))
          .toList(),
      subtotalHt: (json['subtotalHt'] as num?)?.toDouble() ?? 0.0,
      vatRate: (json['vatRate'] as num?)?.toDouble() ?? 0.10,
      vatAmount: (json['vatAmount'] as num?)?.toDouble() ?? 0.0,
      totalTtc: (json['totalTtc'] as num?)?.toDouble() ?? 0.0,
      status: json['status'] as String? ?? 'En attente',
      paymentStatus: json['paymentStatus'] as String? ?? 'unpaid',
      clientLeftWithoutPaying:
          json['clientLeftWithoutPaying'] as bool? ?? false,
      isSentToManager: json['isSentToManager'] as bool? ?? true,
      paymentDeadline: json['paymentDeadline'] != null
          ? parseDate(json['paymentDeadline'])
          : null,
      paymentSecurityCode: json['paymentSecurityCode'] as String?,
    );
  }

  OrderModel copyWith({
    String? id,
    DateTime? createdAt,
    String? customerName,
    String? customerPhone,
    String? orderType,
    String? tableNumber,
    String? deliveryAddress,
    String? paymentMethod,
    String? specialNotes,
    List<CartItemModel>? items,
    double? subtotalHt,
    double? vatRate,
    double? vatAmount,
    double? totalTtc,
    String? status,
    String? paymentStatus,
    bool? clientLeftWithoutPaying,
    bool? isSentToManager,
    DateTime? paymentDeadline,
    bool clearPaymentDeadline = false,
    String? paymentSecurityCode,
  }) {
    return OrderModel(
      id: id ?? this.id,
      createdAt: createdAt ?? this.createdAt,
      customerName: customerName ?? this.customerName,
      customerPhone: customerPhone ?? this.customerPhone,
      orderType: orderType ?? this.orderType,
      tableNumber: tableNumber ?? this.tableNumber,
      deliveryAddress: deliveryAddress ?? this.deliveryAddress,
      paymentMethod: paymentMethod ?? this.paymentMethod,
      specialNotes: specialNotes ?? this.specialNotes,
      items: items ?? this.items,
      subtotalHt: subtotalHt ?? this.subtotalHt,
      vatRate: vatRate ?? this.vatRate,
      vatAmount: vatAmount ?? this.vatAmount,
      totalTtc: totalTtc ?? this.totalTtc,
      status: status ?? this.status,
      paymentStatus: paymentStatus ?? this.paymentStatus,
      clientLeftWithoutPaying:
          clientLeftWithoutPaying ?? this.clientLeftWithoutPaying,
      isSentToManager: isSentToManager ?? this.isSentToManager,
      paymentDeadline:
          clearPaymentDeadline ? null : (paymentDeadline ?? this.paymentDeadline),
      paymentSecurityCode: paymentSecurityCode ?? this.paymentSecurityCode,
    );
  }
}
